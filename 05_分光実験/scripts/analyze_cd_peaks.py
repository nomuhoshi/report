def fwhm(data,base=None):
    xs=np.array([d[0] for d in data],float); ys=np.array([d[1] for d in data])
    if base is None: base=min(ys)
    pk=ys.max(); half=base+(pk-base)/2; i=ys.argmax()
    def cross(a,b):
        for k in range(a,b,(1 if b>a else -1)):
            if (ys[k]-half)*(ys[k+(1 if b>a else -1)]-half)<=0:
                x1,y1,x2,y2=xs[k],ys[k],xs[k+(1 if b>a else -1)],ys[k+(1 if b>a else -1)]
                return x1+(half-y1)*(x2-x1)/(y2-y1)
        return None
    lo=cross(i,0); hi=cross(i,len(xs)-1)
    return xs[i],pk,base,lo,hi,(hi-lo if lo and hi else None)
